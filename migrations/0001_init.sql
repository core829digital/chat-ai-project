-- Schema iniziale su Neon Postgres. Equivalente allo schema SQLite in src/db.js.
-- Le date sono testo 'YYYY-MM-DD HH:MM:SS' in UTC, come in SQLite: stessi confronti e formati.
-- Ogni tabella ha una chiave primaria: è anche il requisito di Neon Realtime (replica identity stabile).

CREATE TABLE accounts (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL,
  plan          TEXT NOT NULL DEFAULT 'pro',
  status        TEXT NOT NULL DEFAULT 'trial',
  sector        TEXT NOT NULL DEFAULT 'generico',
  trial_ends_at TEXT,
  notes         TEXT NOT NULL DEFAULT '',
  created_by    TEXT NOT NULL DEFAULT 'self',
  created_at    TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT NOT NULL,
  name          TEXT NOT NULL DEFAULT '',
  password_hash TEXT,
  role          TEXT NOT NULL CHECK (role IN ('admin','client')),
  account_id    INTEGER REFERENCES accounts(id) ON DELETE CASCADE,
  last_login_at TEXT,
  created_at    TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
-- Email unica senza distinzione tra maiuscole e minuscole (come COLLATE NOCASE in SQLite)
CREATE UNIQUE INDEX users_email_lower ON users (lower(email));

CREATE TABLE sessions (
  token_hash      TEXT PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  impersonator_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  expires_at      TEXT NOT NULL,
  created_at      TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE invites (
  token_hash TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL,
  used_at    TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE widgets (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id       TEXT NOT NULL UNIQUE,
  account_id      INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  site_url        TEXT NOT NULL DEFAULT '',
  allowed_domains TEXT NOT NULL DEFAULT '[]',
  settings        TEXT NOT NULL DEFAULT '{}',
  status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused')),
  last_seen_at    TEXT,
  last_seen_url   TEXT,
  created_at      TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  updated_at      TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE knowledge (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  widget_id  INTEGER NOT NULL REFERENCES widgets(id) ON DELETE CASCADE,
  question   TEXT NOT NULL,
  answer     TEXT NOT NULL,
  keywords   TEXT NOT NULL DEFAULT '',
  hits       INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE conversations (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id     TEXT NOT NULL UNIQUE,
  widget_id     INTEGER NOT NULL REFERENCES widgets(id) ON DELETE CASCADE,
  visitor_id    TEXT NOT NULL,
  page_url      TEXT NOT NULL DEFAULT '',
  is_test       INTEGER NOT NULL DEFAULT 0,
  message_count INTEGER NOT NULL DEFAULT 0,
  unanswered    INTEGER NOT NULL DEFAULT 0,
  has_lead      INTEGER NOT NULL DEFAULT 0,
  started_at    TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  last_at       TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE messages (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  role            TEXT NOT NULL CHECK (role IN ('visitor','bot')),
  body            TEXT NOT NULL,
  knowledge_id    INTEGER REFERENCES knowledge(id) ON DELETE SET NULL,
  outcome         TEXT NOT NULL DEFAULT '',
  created_at      TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE leads (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  widget_id       INTEGER NOT NULL REFERENCES widgets(id) ON DELETE CASCADE,
  conversation_id INTEGER REFERENCES conversations(id) ON DELETE SET NULL,
  name            TEXT NOT NULL DEFAULT '',
  email           TEXT NOT NULL DEFAULT '',
  phone           TEXT NOT NULL DEFAULT '',
  message         TEXT NOT NULL DEFAULT '',
  status          TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','contacted','closed')),
  is_test         INTEGER NOT NULL DEFAULT 0,
  created_at      TEXT NOT NULL DEFAULT to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX idx_widgets_account ON widgets(account_id);
CREATE INDEX idx_knowledge_widget ON knowledge(widget_id);
CREATE INDEX idx_conv_widget ON conversations(widget_id, started_at);
CREATE INDEX idx_conv_widget_last ON conversations(widget_id, last_at DESC);
CREATE INDEX idx_msg_conv ON messages(conversation_id, id);
CREATE INDEX idx_leads_widget ON leads(widget_id, created_at);
CREATE INDEX idx_sessions_user ON sessions(user_id);
